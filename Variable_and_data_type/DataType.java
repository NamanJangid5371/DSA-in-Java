public class DataType {
    public static void main(String[] args) {
        byte a = 8;
        System.out.println(a);
        char ch = 'a';
        System.out.println(ch);
        boolean val = true;
        System.out.println(val);
        float price = 10.5f;
        System.out.println(price);
        int num = 25;
        System.out.println(num);
        Short n = 256;
        System.out.println(n);
    }
}
